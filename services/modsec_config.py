#!/usr/bin/env python3.9
"""
ModSecurity rule-set management for the dispatcher sandbox.

Customers drop their own rule files (*.conf + the *.data files they reference) into
./modsecurity/ on the host, mounted at RULES_DIR. Nothing is built in.

Rule "families" mirror how rule sets are commonly activated in production: a rule file and its
`_logonly` twin (same rule IDs) are one family, and only one variant may be loaded at a time
(like the symlinks in /etc/httpd/modsecurity.d/activated_rules/). Every family has a mode:
  pair   -> "block" | "logonly" | "off"
  single -> "on" | "off"
Modes are stored in the sandbox prefs file so ./modsecurity/ stays an exact copy of the
customer's files.

Generated files (outside RULES_DIR):
  sandbox_rules.conf   Include lines for the active rule files (load order: rules dir root,
                       then sub-directories, then local_rules/ — like production)
  sandbox_engine.conf  SecRuleEngine / SecDebugLogLevel from the control panel

CLI (used by start.sh and watch_filters.sh):
  modsec_config.py apply [--restart]
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

MODSEC_DIR = Path(os.environ.get("MODSEC_DIR", "/etc/httpd/modsecurity.d"))
RULES_DIR = MODSEC_DIR / "rules"
RULES_HOST_DISPLAY = "./modsecurity/"
PREFS_FILE = Path(os.environ.get("SANDBOX_PREFS_FILE", "/etc/httpd/conf.dispatcher.d/filters/.prefs.json"))
MODULE_VALID_SCRIPT = "/usr/local/bin/disp_module_valid.sh"
HTTPD_BIN = "/usr/sbin/httpd"

ENGINE_MODES = ("On", "DetectionOnly", "Off")
# What the Testing tab exercises: both layers, dispatcher filters only (ModSecurity engine forced
# Off) or ModSecurity only (dispatcher filters replaced with an allow-all stub).
TEST_SCOPES = ("both", "filters", "modsec")
FILTER_SCOPE_FILE = Path(os.environ.get("FILTER_SCOPE_FILE", "/etc/httpd/conf.dispatcher.d/sandbox_filters.any"))
FILTERS_GLOB = "/etc/httpd/conf.dispatcher.d/filters/*.any"
DEBUG_LEVELS = (0, 1, 2, 3, 4, 5, 9)
PAIR_MODES = ("block", "logonly", "off")
SINGLE_MODES = ("on", "off")
EDITABLE_SUFFIXES = (".conf", ".data")
MAX_FILE_CHARS = 512_000

_DATA_REF_RE = re.compile(r"@(?:pmFromFile|ipMatchFromFile|pmf)\s+([^\s\"']+)")
_ID_RE = re.compile(r"""(?:^|[\s,"'])id\s*:\s*['"]?(\d+)""")


# ── prefs ────────────────────────────────────────────────────────────────────

def read_prefs() -> Dict[str, Any]:
    try:
        data = json.loads(PREFS_FILE.read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else {}
    except (OSError, json.JSONDecodeError):
        return {}


def write_prefs(updates: Dict[str, Any]) -> None:
    prefs = read_prefs()
    prefs.update(updates)
    PREFS_FILE.write_text(json.dumps(prefs, indent=2) + "\n", encoding="utf-8")


def test_scope(prefs: Optional[Dict[str, Any]] = None) -> str:
    prefs = read_prefs() if prefs is None else prefs
    scope = prefs.get("test_scope", "both")
    return scope if scope in TEST_SCOPES else "both"


def write_filter_scope(scope: Optional[str] = None) -> None:
    scope = scope or test_scope()
    if scope == "modsec":
        text = ('# Generated by the control panel — test scope: ModSecurity only.\n'
                '# Your filters/*.any files are NOT loaded; everything passes the dispatcher.\n'
                '/sandbox-modsec-only-allow-all { /type "allow" /url "*" }\n')
    else:
        text = '# Generated by the control panel — test scope: %s.\n$include "%s"\n' % (scope, FILTERS_GLOB)
    FILTER_SCOPE_FILE.write_text(text, encoding="utf-8")


def engine_settings(prefs: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    prefs = read_prefs() if prefs is None else prefs
    engine = prefs.get("modsec_engine", "On")
    if engine not in ENGINE_MODES:
        engine = "On"
    level = prefs.get("modsec_debug_level", 0)
    if level not in DEBUG_LEVELS:
        level = 0
    return {"engine": engine, "debug_level": level}


# ── discovery ────────────────────────────────────────────────────────────────

def safe_rel_path(rel: str) -> Optional[str]:
    """Validate a path relative to RULES_DIR (no traversal, no hidden parts)."""
    if not isinstance(rel, str) or not rel or len(rel) > 300 or "\\" in rel or rel.startswith("/"):
        return None
    parts = rel.split("/")
    if any(p in ("", ".", "..") or p.startswith(".") for p in parts):
        return None
    if not re.fullmatch(r"[A-Za-z0-9._/@+-]+", rel):
        return None
    return rel


def _iter_files(root: Path, suffix: str) -> List[str]:
    out: List[str] = []
    if not root.is_dir():
        return out
    for dirpath, dirnames, filenames in os.walk(root, followlinks=True):
        dirnames[:] = sorted(d for d in dirnames if not d.startswith("."))
        for name in filenames:
            if name.startswith(".") or not name.endswith(suffix):
                continue
            rel = os.path.relpath(os.path.join(dirpath, name), root).replace(os.sep, "/")
            if safe_rel_path(rel):
                out.append(rel)
    return out


def _load_order_key(rel: str) -> Tuple[int, str]:
    # Production order: modsecurity.d/*.conf, then activated_rules/*.conf, then local_rules/*.conf
    if "/" not in rel:
        return (0, rel)
    if rel.startswith("local_rules/"):
        return (2, rel)
    return (1, rel)


def conf_files(root: Path = RULES_DIR) -> List[str]:
    return sorted(_iter_files(root, ".conf"), key=_load_order_key)


def data_files(root: Path = RULES_DIR) -> List[str]:
    return sorted(_iter_files(root, ".data"))


def families(root: Path = RULES_DIR) -> List[Dict[str, Any]]:
    """Group *.conf files into block/logonly pairs and singles (keyed by the block-variant path)."""
    confs = conf_files(root)
    present = set(confs)
    fams: Dict[str, Dict[str, Any]] = {}
    for rel in confs:
        if rel.endswith("_logonly.conf"):
            key = rel[: -len("_logonly.conf")] + ".conf"
            fam = fams.setdefault(key, {"key": key, "variants": {}})
            fam["variants"]["logonly"] = rel
        else:
            fam = fams.setdefault(rel, {"key": rel, "variants": {}})
            fam["variants"]["block"] = rel
    out: List[Dict[str, Any]] = []
    for key in sorted(fams, key=_load_order_key):
        fam = fams[key]
        v = fam["variants"]
        fam["kind"] = "pair" if ("block" in v and "logonly" in v) else "single"
        if fam["kind"] == "single":
            fam["file"] = v.get("block") or v.get("logonly")
        fam["exists"] = all(p in present for p in v.values())
        out.append(fam)
    return out


def resolve_modes(fams: List[Dict[str, Any]], saved: Optional[Dict[str, str]]) -> Dict[str, str]:
    """Saved mode per family, defaulting new files to block (pairs) / on (singles)."""
    saved = saved or {}
    modes: Dict[str, str] = {}
    for fam in fams:
        m = saved.get(fam["key"])
        allowed = PAIR_MODES if fam["kind"] == "pair" else SINGLE_MODES
        if m not in allowed:
            # A pair saved while it was a single (or vice versa) maps across sensibly.
            if fam["kind"] == "pair":
                m = "off" if m == "off" else "block"
            else:
                m = "off" if m == "off" else "on"
        modes[fam["key"]] = m
    return modes


def active_files(fams: List[Dict[str, Any]], modes: Dict[str, str]) -> List[str]:
    out: List[str] = []
    for fam in fams:
        m = modes.get(fam["key"], "off")
        if fam["kind"] == "pair":
            if m in ("block", "logonly"):
                out.append(fam["variants"][m])
        elif m == "on":
            out.append(fam["file"])
    return sorted(out, key=_load_order_key)


# ── analysis ─────────────────────────────────────────────────────────────────

def _logical_lines(text: str) -> List[Tuple[int, str]]:
    """Join backslash-continued lines; returns (first_line_no, text)."""
    out: List[Tuple[int, str]] = []
    buf = ""
    start = 0
    for i, line in enumerate(text.splitlines(), 1):
        if not buf:
            start = i
        stripped = line.rstrip()
        if stripped.endswith("\\"):
            buf += stripped[:-1] + " "
            continue
        buf += line
        out.append((start, buf))
        buf = ""
    if buf:
        out.append((start, buf))
    return out


def referenced_data(rel: str, root: Path = RULES_DIR) -> List[Dict[str, Any]]:
    """@pmFromFile / @ipMatchFromFile references in a rule file, resolved relative to the file."""
    path = root / rel
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return []
    refs: List[Dict[str, Any]] = []
    seen = set()
    for _, line in _logical_lines(text):
        if line.lstrip().startswith("#"):
            continue
        for m in _DATA_REF_RE.finditer(line):
            ref = m.group(1)
            if ref in seen:
                continue
            seen.add(ref)
            if ref.startswith("/"):
                target = Path(ref)
                target_rel = None
            else:
                target = (path.parent / ref)
                try:
                    target_rel = os.path.relpath(os.path.normpath(str(target)), str(root)).replace(os.sep, "/")
                except ValueError:
                    target_rel = None
            refs.append({"ref": ref, "path": str(target), "rel": target_rel, "exists": target.exists()})
    return refs


def rule_ids(rel: str, root: Path = RULES_DIR) -> List[str]:
    try:
        text = (root / rel).read_text(encoding="utf-8", errors="replace")
    except OSError:
        return []
    ids: List[str] = []
    for _, line in _logical_lines(text):
        s = line.lstrip()
        if s.startswith("#") or not re.match(r"(?i)Sec(Rule|Action)\b", s):
            continue
        m = _ID_RE.search(s)
        if m:
            ids.append(m.group(1))
    return ids


def duplicate_ids(files: List[str], root: Path = RULES_DIR) -> List[Dict[str, Any]]:
    owners: Dict[str, List[str]] = {}
    for rel in files:
        for rid in rule_ids(rel, root):
            owners.setdefault(rid, []).append(rel)
    return [{"id": rid, "files": f} for rid, f in sorted(owners.items()) if len(f) > 1]


# ── generation / validation ──────────────────────────────────────────────────

def write_generated(target_dir: Path, files: List[str], settings: Dict[str, Any]) -> None:
    lines = ["# Generated by the control panel — active ModSecurity rule files (do not edit)."]
    engine = "Off" if test_scope() == "filters" else settings["engine"]
    for rel in files:
        lines.append('Include "${MODSEC_ROOT}/rules/%s"' % rel)
    (target_dir / "sandbox_rules.conf").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (target_dir / "sandbox_engine.conf").write_text(
        "# Generated by the control panel (do not edit).\n"
        "SecRuleEngine %s\nSecDebugLogLevel %d\n" % (engine, settings["debug_level"]),
        encoding="utf-8",
    )


def ensure_data_placeholders(files: List[str], root: Path = RULES_DIR) -> List[str]:
    """Touch empty .data files referenced by active rules but missing (as production installers commonly do)."""
    created: List[str] = []
    for rel in files:
        for ref in referenced_data(rel, root):
            if ref["exists"] or not ref["rel"] or ref["rel"].startswith(".."):
                continue
            p = root / ref["rel"]
            try:
                p.parent.mkdir(parents=True, exist_ok=True)
                p.touch()
                created.append(ref["rel"])
            except OSError:
                pass
    return created


def module_installed() -> bool:
    try:
        return subprocess.run([MODULE_VALID_SCRIPT], capture_output=True, timeout=15).returncode == 0
    except Exception:
        return False


def httpd_config_test(stage_root: Optional[str] = None) -> Tuple[Optional[bool], str]:
    """Run `httpd -t`; (None, msg) when it can't run yet (dispatcher module not installed)."""
    if not module_installed():
        return None, "mod_dispatcher.so is not installed yet — config test skipped."
    cmd = [HTTPD_BIN]
    if stage_root:
        cmd += ["-C", "Define MODSEC_ROOT %s" % stage_root]
    cmd.append("-t")
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=60)
    except Exception as e:
        return False, str(e)
    out = (r.stdout + r.stderr).strip()
    if stage_root:
        out = out.replace(stage_root.rstrip("/") + "/rules/", RULES_HOST_DISPLAY)
    out = out.replace(str(RULES_DIR) + "/", RULES_HOST_DISPLAY)
    return r.returncode == 0, out[:8000]


def plan(saved_modes: Optional[Dict[str, str]] = None, root: Path = RULES_DIR) -> Dict[str, Any]:
    fams = families(root)
    modes = resolve_modes(fams, saved_modes if saved_modes is not None else read_prefs().get("modsec_rules"))
    files = active_files(fams, modes)
    return {"families": fams, "modes": modes, "active": files}


def validate(
    modes: Optional[Dict[str, str]] = None,
    settings: Optional[Dict[str, Any]] = None,
    file_overrides: Optional[Dict[str, str]] = None,
) -> Dict[str, Any]:
    """
    Syntax-check a candidate configuration (pending modes / settings / file edits) in a throwaway
    staged copy of the rules directory. The live files are not touched.
    """
    settings = settings or engine_settings()
    root = tempfile.mkdtemp(prefix="modsec-stage-")
    try:
        stage_rules = Path(root) / "rules"
        if RULES_DIR.is_dir():
            shutil.copytree(RULES_DIR, stage_rules, symlinks=False,
                            ignore=shutil.ignore_patterns(".*"))
        else:
            stage_rules.mkdir()
        for rel, content in (file_overrides or {}).items():
            p = stage_rules / rel
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(content, encoding="utf-8")
        p_ = plan(modes, stage_rules)
        placeholders = ensure_data_placeholders(p_["active"], stage_rules)
        dups = duplicate_ids(p_["active"], stage_rules)
        write_generated(Path(root), p_["active"], settings)
        ok, output = httpd_config_test(root)
        return {"valid": ok, "output": output, "active": p_["active"], "modes": p_["modes"],
                "placeholders": placeholders, "duplicate_ids": dups}
    except OSError as e:
        return {"valid": False, "output": str(e), "active": [], "modes": {}, "placeholders": [], "duplicate_ids": []}
    finally:
        shutil.rmtree(root, ignore_errors=True)


def apply_live(modes: Optional[Dict[str, str]] = None, settings: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    """Write the generated include files for the live rules directory."""
    settings = settings or engine_settings()
    p_ = plan(modes)
    placeholders = ensure_data_placeholders(p_["active"])
    write_generated(MODSEC_DIR, p_["active"], settings)
    return {"active": p_["active"], "modes": p_["modes"], "placeholders": placeholders}


def main(argv: List[str]) -> int:
    if len(argv) < 2 or argv[1] != "apply":
        print(__doc__)
        return 2
    restart = "--restart" in argv
    if restart and module_installed():
        # Check before touching the live include files so a broken edit can't take httpd down.
        v = validate()
        if v["valid"] is False:
            print("[modsec] httpd config test FAILED — keeping the previous ModSecurity config:")
            print(v["output"])
            return 1
    if not restart:
        write_filter_scope()
    res = apply_live()
    for rel in res["placeholders"]:
        print("[modsec] Created empty placeholder for missing data file: %s%s" % (RULES_HOST_DISPLAY, rel))
    print("[modsec] Active rule files (%d): %s" % (len(res["active"]), ", ".join(res["active"]) or "(none)"))
    if restart and module_installed():
        r = subprocess.run(["supervisorctl", "restart", "dispatcher"], capture_output=True, text=True)
        print("[modsec] dispatcher restart: %s" % (r.stdout.strip() or r.stderr.strip()))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
